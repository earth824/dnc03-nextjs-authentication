import NextAuth from 'next-auth';
import Credentials from 'next-auth/providers/credentials';
import GitHub from 'next-auth/providers/github';
import Google from 'next-auth/providers/google';
import z from 'zod';
import { prisma } from './prisma';

const loginSchema = z.object({
  email: z.email(),
  password: z.string().min(1)
});

export const { handlers, signIn, auth, signOut } = NextAuth({
  providers: [
    Google,
    Credentials({
      async authorize(input) {
        // this fn will tell login is success or not
        // - throw error or return null mean fail to login
        // login logic
        const data = loginSchema.parse(input);
        const user = await prisma.user.findUnique({
          where: { email: data.email }
        });

        if (!user) {
          return null;
        }
        // skip: compare password

        return {
          email: user.email,
          id: user.id.toString(),
          name: 'Test',
          image: 'newimage',
          role: 'USER'
        };
      }
    }),
    GitHub
  ],
  callbacks: {
    session({ session, token }) {
      // session parameter is a default session generated by auth.js
      // default: { user: { email, image, name }, expires }
      // token parameter is a payload extract from jwt cookie
      // console.log('------------------------------------');
      // console.log(token);
      // console.log('------------------------------------');
      session.user.id = token.sub!;
      session.user.role = token.role;
      return session;
    }, // this function will be called when: await auth()
    jwt({ token, user }) {
      // token parameter is
      // after success sign in: a default payload generated by auth.js
      // await auth: extract from cookie and success verify
      // user parameter is object return from authorize when signin success
      // await auth: user is null or undefined
      if (user) {
        token.role = user.role;
      }
      console.log('_++++++++++++++++++++++++++++++++++++');
      console.log(token);
      console.log('------------------------------------');
      return token;
    } // this function will be called when: await auth(), after success signIn
  }
});
